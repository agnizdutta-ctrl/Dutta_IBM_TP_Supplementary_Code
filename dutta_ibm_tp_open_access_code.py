    def fB(Bv):
        if Bv <= 0: return PARAMS["rho"]
        Aq = Aqss(Bv, Hv, PARAMS)
        return PARAMS["r"]*Bv*(Bv/th-1.0)*max(1.0-Bv/K,0.0)-PARAMS["delta"]*Aq*Bv+PARAMS["rho"]
    Bs = np.linspace(0.001, 2.5, 4000)
    fs = np.array([fB(b) for b in Bs])
    roots = []
    for i in range(len(fs)-1):
        if fs[i]*fs[i+1] < 0:
            try: roots.append(brentq(fB, Bs[i], Bs[i+1], xtol=1e-8))
            except: pass
    B_nc_low.append(min(roots) if roots else np.nan)
    B_nc_high.append(max(roots) if len(roots) >= 2 else np.nan)
    B_nc_sad.append(sorted(roots)[1] if len(roots) >= 3 else np.nan)
