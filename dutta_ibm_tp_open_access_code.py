def routh_hurwitz(eigs):
    """
    Routh-Hurwitz conditions for a 3×3 Jacobian.
    Characteristic polynomial: λ³ + a1 λ² + a2 λ + a3 = 0
    Stable iff: a1 > 0, a3 > 0, a1*a2 - a3 > 0.
    """
    coeffs = np.poly(eigs)   # [1, a1, a2, a3]
    a1, a2, a3 = coeffs[1], coeffs[2], coeffs[3]
    return a1, a2, a3, (a1 > 0), (a3 > 0), (a1*a2 - a3 > 0)

