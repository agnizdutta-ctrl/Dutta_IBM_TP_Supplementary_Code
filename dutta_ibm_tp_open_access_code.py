# ── 3D A* reconstruction helper ──────────────────────────────────────────
def Aqss_fp(B, H, p):
    """Reconstruct A* from the quasi-steady-state formula."""
    return p["sigma"] * B / ((p["mu_A"] + p["gamma"] * H) * (1.0 + p["kappa"] * B))

# ── Exact 3D Jacobian ─────────────────────────────────────────────────────
def jacobian_3d(B, A, H, p):
    """
    Full 3×3 Jacobian of the IBM-TP system evaluated at (B, A, H).
    Rows: [∂(dB/dt), ∂(dA/dt), ∂(dH/dt)]
    Cols: [∂/∂B,     ∂/∂A,     ∂/∂H    ]
    """
    K     = p["K0"]     * np.exp( p["alpha"]   * H)
    th    = p["theta0"] * np.exp(-p["beta_th"] * H)
    r     = p["r"];  delta = p["delta"]; sigma = p["sigma"]
    mu_A  = p["mu_A"]; gamma = p["gamma"]; kappa = p["kappa"]
    eps   = p["epsilon"]; nu = p["nu"]
    alpha = p["alpha"]; beta_th = p["beta_th"]

    # Row 1: ∂(dB/dt)/∂B, ∂(dB/dt)/∂A, ∂(dB/dt)/∂H
    J11 = r * ((B/th - 1.0)*(1.0 - B/K) + (B/th)*(1.0 - B/K) - (B/K)*(B/th - 1.0)) - delta * A
    J12 = -delta * B
    J13 = r * B * (alpha * (B/K) * (B/th - 1.0) + beta_th * (B/th) * (1.0 - B/K))

    # Row 2: ∂(dA/dt)/∂B, ∂(dA/dt)/∂A, ∂(dA/dt)/∂H
    J21 = sigma / (1.0 + kappa * B)**2
    J22 = -mu_A - gamma * H
    J23 = -gamma * A

    # Row 3: ∂(dH/dt)/∂B, ∂(dH/dt)/∂A, ∂(dH/dt)/∂H
    J31 = eps * (1.0 - H)
    J32 = -nu * H
    J33 = -eps * B - nu * A

    return np.array([[J11, J12, J13],
                     [J21, J22, J23],
                     [J31, J32, J33]])

