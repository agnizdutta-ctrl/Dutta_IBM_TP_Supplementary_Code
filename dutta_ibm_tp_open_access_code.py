# ── ODE system ────────────────────────────────────────────────────────────
def ibm_tp(t, y, p):
    B, A, H = y
    B = max(B, 0.0); A = max(A, 0.0); H = np.clip(H, 0.0, 1.0)
    K     = p["K0"]    * np.exp( p["alpha"]   * H)
    theta = p["theta0"]* np.exp(-p["beta_th"] * H)
    dB = p["r"]*B*(B/theta - 1.0)*max(1.0 - B/K, 0.0) - p["delta"]*A*B + p["rho"]
    dA = p["sigma"]*B / (1.0 + p["kappa"]*B) - p["mu_A"]*A - p["gamma"]*H*A
    dH = p["epsilon"]*B*(1.0 - H) - p["nu"]*A*H
    return [dB, dA, dH]

def Aqss(B, H, p):
    return p["sigma"]*B / ((p["mu_A"] + p["gamma"]*H + 1e-9)*(1.0 + p["kappa"]*B + 1e-9))

